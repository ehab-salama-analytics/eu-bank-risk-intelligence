@dataclass
class CheckResult:
    """One validation result."""

    table: str
    check: str
    status: str
    message: str


@dataclass
class ValidationReport:
    """Collect validation results for final reporting."""

    results: list[CheckResult] = field(default_factory=list)

    def add(
        self,
        table: str,
        check: str,
        status: str,
        message: str,
    ) -> None:

        result = CheckResult(
            table=table,
            check=check,
            status=status,
            message=message,
        )

        self.results.append(result)

        print(
            f"[{status:<7}] "
            f"{table:<28} | "
            f"{check:<28} | "
            f"{message}"
        )

    def pass_check(
        self,
        table: str,
        check: str,
        message: str,
    ) -> None:

        self.add(
            table,
            check,
            "PASS",
            message,
        )

    def warning(
        self,
        table: str,
        check: str,
        message: str,
    ) -> None:

        self.add(
            table,
            check,
            "WARNING",
            message,
        )

    def fail(
        self,
        table: str,
        check: str,
        message: str,
    ) -> None:

        self.add(
            table,
            check,
            "FAIL",
            message,
        )

    def status_counts(self) -> dict[str, int]:

        counts = {
            "PASS": 0,
            "WARNING": 0,
            "FAIL": 0,
        }

        for result in self.results:
            counts[result.status] += 1

        return counts

    def tables_with_status(
        self,
        status: str,
    ) -> list[str]:

        return sorted(
            {
                result.table
                for result in self.results
                if result.status == status
            }
        )


# =============================================================================
# General helper functions
# =============================================================================

def to_snake_case(
    column_name: str,
) -> str:
    """
    Same column-name standardisation used by
    build_reference_tables.py.

    Validation only: no DataFrame columns are modified.
    """

    column_name = str(column_name).strip()

    column_name = re.sub(
        r"[^A-Za-z0-9]+",
        "_",
        column_name,
    )

    column_name = re.sub(
        r"_+",
        "_",
        column_name,
    )

    return column_name.strip("_").lower()


def count_blank_values(
    series: pd.Series,
) -> int:
    """
    Count empty or whitespace-only non-null values.
    """

    non_null = series.dropna()

    if non_null.empty:
        return 0

    values = non_null.astype("string")

    return int(
        values.str.strip().eq("").sum()
    )


def count_whitespace_values(
    series: pd.Series,
) -> int:
    """
    Count values containing leading/trailing whitespace.
    """

    non_null = series.dropna()

    if non_null.empty:
        return 0

    values = non_null.astype("string")

    return int(
        values.ne(values.str.strip()).sum()
    )


def duplicate_statistics(
    series: pd.Series,
) -> tuple[int, int]:
    """
    Return:

        duplicate_rows
        duplicated_distinct_values

    Null values are excluded because missingness is tested separately.
    """

    non_null = series.dropna()

    if non_null.empty:
        return 0, 0

    mask = non_null.duplicated(
        keep=False
    )

    duplicate_rows = int(
        mask.sum()
    )

    duplicate_values = int(
        non_null.loc[mask]
        .nunique(dropna=True)
    )

    return (
        duplicate_rows,
        duplicate_values,
    )


def duplicate_examples(
    series: pd.Series,
    max_examples: int = 5,
) -> str:

    non_null = series.dropna()

    mask = non_null.duplicated(
        keep=False
    )

    examples = (
        non_null.loc[mask]
        .astype("string")
        .drop_duplicates()
        .head(max_examples)
        .tolist()
    )

    if not examples:
        return "None"

    return ", ".join(
        repr(value)
        for value in examples
    )


