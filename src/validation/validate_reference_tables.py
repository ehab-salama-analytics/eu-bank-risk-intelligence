def validate_reference_directory(
    report: ValidationReport,
) -> bool:

    if not REFERENCE_DIR.exists():

        report.fail(
            "REFERENCE_LAYER",
            "directory_exists",
            f"Directory does not exist: {REFERENCE_DIR}",
        )

        return False

    if not REFERENCE_DIR.is_dir():

        report.fail(
            "REFERENCE_LAYER",
            "directory_type",
            f"Path is not a directory: {REFERENCE_DIR}",
        )

        return False

    report.pass_check(
        "REFERENCE_LAYER",
        "directory_exists",
        f"Reference staging directory found: {REFERENCE_DIR}",
    )

    return True


def validate_expected_file_set(
    report: ValidationReport,
) -> None:

    expected = {
        spec.file_name
        for spec in TABLE_SPECS.values()
    }

    actual = {
        path.name
        for path in REFERENCE_DIR.glob("*.parquet")
        if path.is_file()
    }

    unexpected = sorted(
        actual - expected
    )

    if unexpected:

        report.warning(
            "REFERENCE_LAYER",
            "unexpected_files",
            "Additional Parquet file(s): "
            + ", ".join(unexpected),
        )

    else:

        report.pass_check(
            "REFERENCE_LAYER",
            "unexpected_files",
            "No unexpected Parquet files found",
        )


